-- =====================================================================
-- ARAÇLAR — araç bazlı gider takibi
-- =====================================================================
-- Araçlar hesap sisteminden BAĞIMSIZDIR: `hesaplar` ağacında yer almaz,
-- bakiyeleri yoktur, dönem kapanışlarına girmez. Tek işlevleri Akaryakıt /
-- Ulaşım kategorili giderleri bir araca etiketlemek — böylece Araç sayfası
-- aylık ve ortalama araç giderini gösterebilir.
--
-- arac_id üç tabloya birden eklenir, çünkü bir akaryakıt gideri üç yoldan
-- doğabiliyor ve hepsinin sonunda aynı yere (hesap_hareketler) varması gerekiyor:
--   1) Hesap sayfasından doğrudan gider → hesap_hareketler.arac_id
--   2) KK tek çekim harcaması          → borc_harcamalar.arac_id
--                                        → ekstre kesilince borc_kalemler.arac_id
--                                        → ekstre ödenince hesap_hareketler.arac_id
--   3) KK taksitli harcaması           → borc_kalemler.arac_id
--                                        → ekstre ödenince hesap_hareketler.arac_id
-- Raporlama tek noktadan (hesap_hareketler) yapılır; diğer ikisi ara duraktır.
-- =====================================================================

create table if not exists araclar (
  id bigint generated by default as identity primary key,
  ad text not null,
  plaka text,
  emoji text,
  alis_tarihi date,
  -- aktif=false → satıldı. satis_tarihi ortalama hesabında bitiş ayını verir.
  satis_tarihi date,
  aktif boolean not null default true,
  sira integer,
  aciklama text,
  created_at timestamptz default now()
);

alter table araclar enable row level security;

create policy "Sadece giris yapanlar" on araclar
  for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

alter table hesap_hareketler add column if not exists arac_id bigint references araclar(id);
alter table borc_harcamalar add column if not exists arac_id bigint references araclar(id);
alter table borc_kalemler   add column if not exists arac_id bigint references araclar(id);

create index if not exists idx_hesap_hareketler_arac_id on hesap_hareketler(arac_id);
create index if not exists idx_borc_harcamalar_arac_id  on borc_harcamalar(arac_id);
create index if not exists idx_borc_kalemler_arac_id    on borc_kalemler(arac_id);

